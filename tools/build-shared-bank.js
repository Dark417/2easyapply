// Build the unified cross-platform question bank (BETA — see AGENTS.md "Unified question base").
//
// Extracts DEFAULT_APPLICATION_QUESTIONS + DEFAULT_VOLUNTARY_DISCLOSURES from eve/workday.js and
// DEFAULT_GH_QUESTIONS from eve/greenhouse.js VERBATIM (regexes are never retyped — see the bank
// control-character lesson in AGENTS.md) and generates eve/question-bank.js, which exposes
// self.EVE_SHARED_QUESTION_BANK. Engines consult it only when the `eveUnifiedBank` storage flag
// is true; with the flag off (default) behavior is exactly the per-engine status quo.
//
// Usage: node tools/build-shared-bank.js   (run after any bank edit, before bump/reload)
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const OUT = path.join(root, 'eve', 'question-bank.js');

function readSource(file) {
    return fs.readFileSync(path.join(root, 'eve', file), 'utf8');
}

// Walk to the matching "];" at bracket depth 0 and return the verbatim array literal text.
function extractArray(source, name, file) {
    const decl = `const ${name} = [`;
    const start = source.indexOf(decl);
    if (start < 0) throw new Error(`${name} not found in ${file}`);
    let depth = 0;
    let index = source.indexOf('[', start);
    for (; index < source.length; index += 1) {
        const ch = source[index];
        if (ch === '[') depth += 1;
        else if (ch === ']') {
            depth -= 1;
            if (depth === 0) break;
        }
    }
    return source.slice(source.indexOf('[', start), index + 1);
}

// The arrays may reference simple string-scalar consts (e.g. SALARY_EXPECTATION). Extract every
// `const NAME = '...';` definition for uppercase identifiers the array text mentions.
function extractScalars(source, arrayTexts) {
    const wanted = new Set();
    for (const text of arrayTexts) {
        for (const m of text.matchAll(/\b[A-Z][A-Z0-9_]{2,}\b/g)) wanted.add(m[0]);
    }
    const defs = [];
    for (const name of wanted) {
        const m = new RegExp(`const ${name} = ('|")([\\s\\S]*?)\\1;`).exec(source);
        if (m) defs.push(`const ${name} = ${JSON.stringify(m[2])};`);
    }
    return defs;
}

const workdaySrc = readSource('workday.js');
const ghSrc = readSource('greenhouse.js');

const appText = extractArray(workdaySrc, 'DEFAULT_APPLICATION_QUESTIONS', 'workday.js');
const volText = extractArray(workdaySrc, 'DEFAULT_VOLUNTARY_DISCLOSURES', 'workday.js');
const ghText = extractArray(ghSrc, 'DEFAULT_GH_QUESTIONS', 'greenhouse.js');
const scalars = [
    ...extractScalars(workdaySrc, [appText, volText]),
    ...extractScalars(ghSrc, [ghText])
];
// Dedupe scalar definitions by name (first wins).
const seenScalar = new Set();
const scalarBlock = scalars.filter(def => {
    const name = def.split(' ')[1];
    if (seenScalar.has(name)) return false;
    seenScalar.add(name);
    return true;
}).map(def => `    ${def}`).join('\n');

const generated = `// GENERATED by tools/build-shared-bank.js — DO NOT EDIT BY HAND.
// Unified cross-platform question bank (BETA). Loaded before each platform engine; consulted
// only when the \`eveUnifiedBank\` chrome.storage.local flag is true. With the flag off
// (default), engines use exactly their own per-platform banks.
(function () {
    'use strict';
${scalarBlock}
    const WORKDAY_APPLICATION_QUESTIONS = ${appText};
    const WORKDAY_VOLUNTARY_DISCLOSURES = ${volText};
    const GREENHOUSE_QUESTIONS = ${ghText};

    const clone = entry => ({ ...entry, patterns: [...entry.patterns] });
    // Cross-pollination: topics one platform knows that the other doesn't. Extras are appended
    // AFTER the engine's own bank (own topics always win) and only when the entry carries an
    // answer shape the target engine can act on.
    function extrasFor(platform) {
        if (platform === 'workday') {
            const own = new Set([...WORKDAY_APPLICATION_QUESTIONS, ...WORKDAY_VOLUNTARY_DISCLOSURES].map(e => e.topic));
            return GREENHOUSE_QUESTIONS
                .filter(e => !own.has(e.topic) && (e.choose || e.optionMatch || e.optionCandidates))
                .map(clone);
        }
        // greenhouse + indeed (Indeed's bank is spliced verbatim from greenhouse's).
        const own = new Set(GREENHOUSE_QUESTIONS.map(e => e.topic));
        return WORKDAY_APPLICATION_QUESTIONS
            .filter(e => !own.has(e.topic) && (e.choose || e.optionMatch || e.optionCandidates || e.text != null))
            .map(clone);
    }

    (typeof self !== 'undefined' ? self : window).EVE_SHARED_QUESTION_BANK = {
        workday: { applicationQuestions: WORKDAY_APPLICATION_QUESTIONS, voluntaryDisclosures: WORKDAY_VOLUNTARY_DISCLOSURES },
        greenhouse: { questions: GREENHOUSE_QUESTIONS },
        extrasFor
    };
})();
`;

fs.writeFileSync(OUT, generated, 'utf8');

// ── Validation ────────────────────────────────────────────────────────────────────────────────
// 1. Control-character guard (the 0x08 lesson).
const written = fs.readFileSync(OUT, 'utf8');
const bad = written.match(/[\x00-\x08\x0b\x0c\x0e-\x1f]/);
if (bad) throw new Error('Control character found in generated question-bank.js');
// 2. Evaluate with a stub `self` and sanity-check the exposed API.
const stub = {};
new Function('self', written)(stub);
const bank = stub.EVE_SHARED_QUESTION_BANK;
if (!bank) throw new Error('EVE_SHARED_QUESTION_BANK not exposed');
const wdExtras = bank.extrasFor('workday');
const ghExtras = bank.extrasFor('greenhouse');
if (!Array.isArray(wdExtras) || !Array.isArray(ghExtras)) throw new Error('extrasFor did not return arrays');
for (const [label, extras, ownList] of [
    ['workday', wdExtras, [...bank.workday.applicationQuestions, ...bank.workday.voluntaryDisclosures]],
    ['greenhouse', ghExtras, bank.greenhouse.questions]
]) {
    const own = new Set(ownList.map(e => e.topic));
    const overlap = extras.filter(e => own.has(e.topic));
    if (overlap.length) throw new Error(`extrasFor('${label}') overlaps own topics: ${overlap.map(e => e.topic).join(', ')}`);
}
console.log(`generated eve/question-bank.js — workday bank ${bank.workday.applicationQuestions.length}+${bank.workday.voluntaryDisclosures.length}, gh bank ${bank.greenhouse.questions.length}, extras: ${wdExtras.length} -> workday, ${ghExtras.length} -> gh/indeed`);
